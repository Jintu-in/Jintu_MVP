/**
 * Concatenates every migration (and optionally the seed) into one script you
 * can paste into the Supabase dashboard SQL editor.
 *
 *   pnpm db:bundle          # migrations only
 *   pnpm db:bundle --seed   # migrations + seed data
 *
 * `supabase db push` is the normal route. This exists because that route
 * needs the CLI logged in with a personal access token and the project's
 * database password, and `supabase start` needs Docker — none of which a
 * person setting the project up for the first time necessarily has to hand.
 * The dashboard SQL editor needs none of them.
 *
 * Ordering is by filename, which is how Supabase orders migrations too, so
 * what you paste is what `db push` would have applied.
 *
 * Caveat worth knowing: applying SQL this way does not record anything in
 * supabase_migrations.schema_migrations, so a later `db push` will try to
 * apply the same files again and fail on "already exists". Once you can run
 * the CLI, either repair the history (`supabase migration repair --status
 * applied <version>`) or reset the database and push properly.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS = path.join(ROOT, "supabase", "migrations");
const SEED = path.join(ROOT, "supabase", "seed.sql");
const OUT_DIR = path.join(ROOT, "supabase", ".bundle");
let OUT = path.join(OUT_DIR, "apply-all.sql");

const withSeed = process.argv.includes("--seed");

/**
 * `--since <prefix>` emits only migrations after the one already applied.
 *
 *   pnpm db:bundle --since 20260809050000
 *
 * Pasting apply-all.sql into a project that is halfway through is not safe in
 * general — the early migrations create tables that already exist, and the
 * first `create table` without `if not exists` aborts the whole script, so you
 * find out by watching it fail rather than by it doing nothing. A catch-up
 * bundle is the smaller, honest artefact: exactly the files that have not run.
 *
 * The prefix is the timestamp of the LAST migration already applied, so the
 * output starts at the one after it.
 */
const sinceFlag = process.argv.indexOf("--since");
const since = sinceFlag === -1 ? null : process.argv[sinceFlag + 1];

if (sinceFlag !== -1 && !since) {
  console.error("--since needs a migration timestamp, e.g. --since 20260809050000");
  process.exit(1);
}

const all = readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith(".sql"))
  .sort();

/**
 * Compared on the timestamp alone, not the filename.
 *
 * `"20260809050000_weekly_loop.sql" > "20260809050000"` is true — same prefix,
 * longer string — so filtering on the raw filename includes the migration you
 * said was already applied. That bundle then opens by re-creating tables that
 * exist, the first `create table` aborts the script, and nothing after it
 * runs. Caught by reading the output rather than by trusting the flag.
 */
const stamp = (f) => f.split("_")[0];

const files = since ? all.filter((f) => stamp(f) > since) : all;

if (since && !all.some((f) => stamp(f) === since)) {
  console.error(
    `--since ${since} does not match any migration. Check the timestamp:\n` +
      all.map((f) => `  ${f}`).join("\n"),
  );
  process.exit(1);
}

if (since && files.length === 0) {
  console.log(`Nothing to bundle — every migration after ${since} is already in this repo's history.`);
  process.exit(0);
}

if (files.length === 0) {
  console.error("No migrations found.");
  process.exit(1);
}

const parts = [
  "-- GENERATED by scripts/bundle-migrations.mjs — do not edit, do not commit.",
  "-- Paste into: Supabase dashboard > SQL Editor > New query > Run.",
  "--",
  "-- This does NOT record migration history. See the note in the script",
  "-- before you later run `supabase db push`.",
  "",
];

for (const file of files) {
  parts.push(
    `-- ${"═".repeat(74)}`,
    `-- ${file}`,
    `-- ${"═".repeat(74)}`,
    "",
    readFileSync(path.join(MIGRATIONS, file), "utf8").trimEnd(),
    "",
  );
}

if (withSeed) {
  if (!existsSync(SEED)) {
    console.error("--seed requested but supabase/seed.sql does not exist.");
    process.exit(1);
  }
  parts.push(
    `-- ${"═".repeat(74)}`,
    "-- seed.sql — sample curriculum, safe to skip in production",
    `-- ${"═".repeat(74)}`,
    "",
    readFileSync(SEED, "utf8").trimEnd(),
    "",
  );
}

if (since) OUT = path.join(OUT_DIR, `catch-up-since-${since}.sql`);
mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, parts.join("\n"), "utf8");

const lines = parts.join("\n").split("\n").length;
console.log(`Bundled ${files.length} migration(s)${withSeed ? " + seed" : ""} -> ${path.relative(ROOT, OUT).replace(/\\/g, "/")}`);
console.log(`${lines} lines. Paste it into the Supabase SQL editor and run it.`);
