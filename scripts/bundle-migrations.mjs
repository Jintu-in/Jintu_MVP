/**
 * Concatenates every migration (and optionally the seed) into one script you
 * can paste into the Supabase dashboard SQL editor.
 *
 *   pnpm db:bundle          # migrations only
 *   pnpm db:bundle --seed   # migrations + seed data
 *
 * `supabase db push` is the normal route. This exists because that route
 * needs the CLI logged in with a personal access token and the project's
 * database password, and `supabase start` needs Docker — none of which a
 * person setting the project up for the first time necessarily has to hand.
 * The dashboard SQL editor needs none of them.
 *
 * Ordering is by filename, which is how Supabase orders migrations too, so
 * what you paste is what `db push` would have applied.
 *
 * Caveat worth knowing: applying SQL this way does not record anything in
 * supabase_migrations.schema_migrations, so a later `db push` will try to
 * apply the same files again and fail on "already exists". Once you can run
 * the CLI, either repair the history (`supabase migration repair --status
 * applied <version>`) or reset the database and push properly.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS = path.join(ROOT, "supabase", "migrations");
const SEED = path.join(ROOT, "supabase", "seed.sql");
const OUT_DIR = path.join(ROOT, "supabase", ".bundle");
const OUT = path.join(OUT_DIR, "apply-all.sql");

const withSeed = process.argv.includes("--seed");

const files = readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  console.error("No migrations found.");
  process.exit(1);
}

const parts = [
  "-- GENERATED by scripts/bundle-migrations.mjs — do not edit, do not commit.",
  "-- Paste into: Supabase dashboard > SQL Editor > New query > Run.",
  "--",
  "-- This does NOT record migration history. See the note in the script",
  "-- before you later run `supabase db push`.",
  "",
];

for (const file of files) {
  parts.push(
    `-- ${"═".repeat(74)}`,
    `-- ${file}`,
    `-- ${"═".repeat(74)}`,
    "",
    readFileSync(path.join(MIGRATIONS, file), "utf8").trimEnd(),
    "",
  );
}

if (withSeed) {
  if (!existsSync(SEED)) {
    console.error("--seed requested but supabase/seed.sql does not exist.");
    process.exit(1);
  }
  parts.push(
    `-- ${"═".repeat(74)}`,
    "-- seed.sql — sample curriculum, safe to skip in production",
    `-- ${"═".repeat(74)}`,
    "",
    readFileSync(SEED, "utf8").trimEnd(),
    "",
  );
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, parts.join("\n"), "utf8");

const lines = parts.join("\n").split("\n").length;
console.log(`Bundled ${files.length} migration(s)${withSeed ? " + seed" : ""} -> ${path.relative(ROOT, OUT).replace(/\\/g, "/")}`);
console.log(`${lines} lines. Paste it into the Supabase SQL editor and run it.`);
